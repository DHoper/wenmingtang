/** 清理客人的叩問：去掉控制字元與多餘空白，截到上限 */
export function cleanQuestion(q) {
  return String(q || "").replace(/[\u0000-\u001f\u007f]/g, " ").replace(/\s+/g, " ").trim().slice(0, LIMITS.QUESTION_MAX);
}

export function messagesFor(basis, question = "", mode = "ask") {
  if (mode === "reading") return [{ role: "system", content: SYSTEM_READING }, { role: "user", content: "批命依據：\n" + JSON.stringify(basis, null, 1) + "\n\n請照格式替他整張批命。" }];
  const q = cleanQuestion(question);
  const user = "批命依據：\n" + JSON.stringify(basis, null, 1) + (q ? `\n\n【客人問】${q}【問完】` : "\n\n（客人沒有特別問什麼，請照整張批命細說。）");
  return [{ role: "system", content: SYSTEM }, { role: "user", content: user }];
}
