const GEN = { 木: "火", 火: "土", 土: "金", 金: "水", 水: "木" }; // 生
const KE = { 木: "土", 土: "水", 水: "火", 火: "金", 金: "木" };  // 剋
export function relation(a, b) {
  if (a === b) return "比和";
  if (GEN[a] === b) return "生";   // a 生 b
  if (GEN[b] === a) return "被生"; // b 生 a
  if (KE[a] === b) return "剋";
  return "被剋";
}

export function levelName(v) {
  return v >= 0.75 ? "大吉" : v >= 0.35 ? "吉" : v >= -0.15 ? "吉凶參半" : v >= -0.6 ? "凶多於吉" : "凶";
}

